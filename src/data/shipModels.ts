export const SHIP_MODEL_MAP = {
  get: (id: string): BaseShipModel | undefined => {
    if (BASE_SHIP_MAP.has(id)) {
      return BASE_SHIP_MAP.get(id);
    }
    const aliasId = LEGACY_SHIP_ALIASES[id];
    if (aliasId && BASE_SHIP_MAP.has(aliasId)) {
      return BASE_SHIP_MAP.get(aliasId);
    }
    return BASE_SHIPS[0];
  },
  has: (id: string): boolean => {
    return BASE_SHIP_MAP.has(id) || Boolean(LEGACY_SHIP_ALIASES[id]);
  },
  values: () => BASE_SHIP_MAP.values(),
  entries: () => BASE_SHIP_MAP.entries(),
  forEach: (cb: (value: BaseShipModel, key: string) => void) => BASE_SHIP_MAP.forEach(cb),
};
